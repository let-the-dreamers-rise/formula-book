// Writes src/card-html.ts from card/: the one self-contained card HTML and its content hash, so the
// server code that serves the card has no file system access and also runs in a browser tab.
// Usage: npm run build:card -w @formula-book/mcp-server (test/card.test.ts fails if it is stale).
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../card/", import.meta.url);
const read = (name) => readFileSync(new URL(name, dir), "utf8");

// Function replacers, so "$" in the CSS or script is never read as a replacement pattern.
export function buildCardHtml() {
  return read("template.html")
    .replace("{{style}}", () => read("card.css"))
    .replace("{{script}}", () => read("card.js"));
}

export const cardHash = (html) => createHash("sha256").update(html).digest("hex").slice(0, 16);

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].replace(/\\/g, "/").split("/").pop())) {
  const html = buildCardHtml();
  const source =
    "// Generated by scripts/build-card.mjs from card/. Do not edit by hand.\n" +
    `export const CARD_HTML = ${JSON.stringify(html)};\n` +
    `export const CARD_HASH = ${JSON.stringify(cardHash(html))};\n`;
  writeFileSync(new URL("../src/card-html.ts", import.meta.url), source);
  console.log(`card-html.ts written, hash ${cardHash(html)}`);
}
